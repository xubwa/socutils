#!/usr/bin/env python
'''
Generator of lib/vhf/md_j_gen.c: unrolled pieces of the McMurchie-Davidson J
engine of md_j.c (included there), replacing its table-driven loops:

  mdr_<L>(R0, pref, theta, X, Y, Z), L <= RLMAX: the Hermite Coulomb integrals
  R^(0)_tuv of degree <= L by the recursion of hermite_R (R^(n)_{t+1} =
  t R^(n+1)_{t-1} + X R^(n+1)_t along the first nonzero component), every
  node a scalar;

  mdc_<lp>_<lq>(R0, rp, rq, vp, vq, up, uq), lp, lq <= CLMAX: the two
  contractions of T_PQ = R_{t+s} (-1)^|s| with the Hermite densities,
  vp_t += sum_s (-1)^|s| R_{t+s} rq_s (up) and vq_s += (-1)^|s| sum_t R_{t+s} rp_t (uq),
  the index map t + s constant.

The Hermite index order is md_j.c's (by degree, then t, then u descending).

    python gen_md_j.py > md_j_gen.c
'''
import sys

RLMAX = 12
CLMAX = 6


def herm(d):
    return [(t, u, d - t - u) for t in range(d, -1, -1) for u in range(d - t, -1, -1)]


def order(L):
    '''md_j.c's order: degree, then t ascending, then u ascending (hermite_tables)'''
    out = []
    for d in range(L + 1):
        for t in range(d + 1):
            for u in range(d - t + 1):
                out.append((t, u, d - t - u))
    return out


def mdr(L):
    idx = {h: i for i, h in enumerate(order(L))}
    o = []
    w = o.append
    w('static void mdr_%d(double *R0, double pref, double theta, double X, double Y, double Z)' % L)
    w('{')
    w('        double F[%d];' % (L + 1))
    w('        boys_fn(F, theta * (X * X + Y * Y + Z * Z), %d);' % L)
    w('        const double m2t = -2 * theta;')
    w('        double f = pref;')
    for n in range(L + 1):
        w('        const double r%d_0 = f * F[%d];' % (n, n))
        if n < L:
            w('        f *= m2t;')
    XYZ = 'XYZ'
    seen = set()
    for (t, u, v) in order(L)[1:]:
        c = (t, u, v)
        k = 0 if t else (1 if u else 2)
        m1 = list(c)
        m1[k] -= 1
        m2 = list(c)
        m2[k] -= 2
        i, i1 = idx[c], idx[tuple(m1)]
        cc = c[k] - 1
        i2 = idx[tuple(m2)] if c[k] >= 2 else None
        d = t + u + v
        for n in range(L - d + 1):
            e = '%s * r%d_%d' % (XYZ[k], n + 1, i1)
            if cc > 0:
                e += ' + %d * r%d_%d' % (cc, n + 1, i2)
            w('        const double r%d_%d = %s;' % (n, i, e))
    for i in range(len(order(L))):
        w('        R0[%d] = r0_%d;' % (i, i))
    w('}')
    return '\n'.join(o)


def nh(d):
    return (d + 1) * (d + 2) * (d + 3) // 6


def mdc(lp, lq):
    L = lp + lq
    idx = {h: i for i, h in enumerate(order(L))}
    P, Q = order(lp), order(lq)
    o = []
    w = o.append
    w('static void mdc_%d_%d(const double *R0, const double *rp, const double *rq, double *vp, double *vq,'
      ' int up, int uq)' % (lp, lq))
    w('{')
    w('        if (up) {')
    for a, ha in enumerate(P):
        terms = []
        for b, hb in enumerate(Q):
            s = '-' if sum(hb) % 2 else '+'
            k = idx[(ha[0] + hb[0], ha[1] + hb[1], ha[2] + hb[2])]
            terms.append('%s R0[%d] * rq[%d]' % (s, k, b))
        e = ' '.join(terms)
        if e.startswith('+ '):
            e = e[2:]
        w('                vp[%d] += %s;' % (a, e))
    w('        }')
    w('        if (uq) {')
    for b, hb in enumerate(Q):
        terms = []
        for a, ha in enumerate(P):
            k = idx[(ha[0] + hb[0], ha[1] + hb[1], ha[2] + hb[2])]
            terms.append('R0[%d] * rp[%d]' % (k, a))
        s = '-' if sum(hb) % 2 else ''
        w('                vq[%d] += %s(%s);' % (b, s, ' + '.join(terms)))
    w('        }')
    w('}')
    return '\n'.join(o)


def main():
    out = ['/* Generated by gen_md_j.py; do not edit.  Included by md_j.c (boys_fn). */', '']
    for L in range(RLMAX + 1):
        out.append(mdr(L))
        out.append('')
    for lp in range(CLMAX + 1):
        for lq in range(CLMAX + 1):
            out.append(mdc(lp, lq))
            out.append('')
    out.append('#define MDR_LMAX %d' % RLMAX)
    out.append('#define MDC_LMAX %d' % CLMAX)
    out.append('typedef void (*mdr_fn)(double *, double, double, double, double, double);')
    out.append('static const mdr_fn mdr_table[%d] = {%s};' % (RLMAX + 1, ', '.join('mdr_%d' % L for L in range(RLMAX + 1))))
    out.append('typedef void (*mdc_fn)(const double *, const double *, const double *, double *, double *, int, int);')
    out.append('static const mdc_fn mdc_table[%d][%d] = {' % (CLMAX + 1, CLMAX + 1))
    for lp in range(CLMAX + 1):
        out.append('        {%s},' % ', '.join('mdc_%d_%d' % (lp, lq) for lq in range(CLMAX + 1)))
    out.append('};')
    sys.stdout.write('\n'.join(out) + '\n')


if __name__ == '__main__':
    main()
