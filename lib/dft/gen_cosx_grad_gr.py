#!/usr/bin/env python
'''
Generate lib/dft/cosx_grad_gr.h: SOCDFTcosx_grad_gr, the COSX gradient kernel SOCDFTcosx_grad of cosx.c with
the grid-response outputs of the same pass (included by cosx_gridresp.c, whose helpers gr_point2 / gr_point4
it calls):

    eg[g]     = sum_ab H_a A_ab F_b                                    (for the partition-weight derivatives)
    pg[x][g]  = w_g d e_g / d r_g,x = w_g sum_i d_x phi_i Q_i          (through the AOs: term (i) per point)
                - sum_pairs sum_t (sum_ab E_ab,t W_ab(g)) R_{t+1x}(g)  (through the integrals, after each W . R)

The rest is SOCDFTcosx_grad verbatim, so rerun this after changing it:

    python lib/dft/gen_cosx_grad_gr.py lib/dft/cosx.c > lib/dft/cosx_grad_gr.h

(Reducing the integral term over the runs of points of one owner atom instead -- W R^T per run, free in
principle -- was measured slower: the box-sorted blocks of 112 points hold ~10 owner atoms.)
'''
import sys

src = open(sys.argv[1]).read()
i0 = src.index('void SOCDFTcosx_grad(double *grad')
i1 = src.index('\n}\n', src.index('free(atm_of);', i0)) + 3
body = src[i0:i1]


def rep(old, new, count=1):
    global body
    assert body.count(old) == count, (old, body.count(old))
    body = body.replace(old, new)


rep('void SOCDFTcosx_grad(double *grad', 'void SOCDFTcosx_grad_gr(double *grad')
rep('dgemm_t dgemm_, mkl_local_t mkl_set_num_threads_local, double *kout)',
    'dgemm_t dgemm_, mkl_local_t mkl_set_num_threads_local, double *kout,\n'
    '                        double *pg, double *eg)')
rep('        memset(grad, 0, sizeof(double) * natm * 3);\n',
    '        memset(grad, 0, sizeof(double) * natm * 3);\n'
    '        memset(pg, 0, sizeof(double) * 3 * (size_t)ngrid);\n'
    '        memset(eg, 0, sizeof(double) * (size_t)ngrid);\n')
rep('        double *R = malloc(sizeof(double) * (size_t)nhmax * blk);\n',
    '        double *R = malloc(sizeof(double) * (size_t)nhmax * blk);\n'
    '        double *V = malloc(sizeof(double) * (size_t)nhmax * blk);\n')
rep('                const double *w = weights + g0;\n',
    '                const double *w = weights + g0;\n'
    '                double *px = pg + g0, *py = pg + (size_t)ngrid + g0, *pz = pg + 2 * (size_t)ngrid + g0;\n'
    '                double *pp[3] = {px, py, pz};\n')
rep('                                        w_dot_r(Mm, W, farR[at], nab, nh1, n, dgemm_);\n',
    '                                        w_dot_r(Mm, W, farR[at], nab, nh1, n, dgemm_);\n'
    '                                        GR_POINT(Mo, farR[at])\n')
rep('                                w_dot_r(Mm, W, R, nab, nh1, n, dgemm_);\n',
    '                                w_dot_r(Mm, W, R, nab, nh1, n, dgemm_);\n'
    '                                GR_POINT(E, R)\n')
rep('                GTICK(1)\n',
    '                GTICK(1)\n'
    '                {\n'
    '                        /* e_g = sum_a H_a G^F_a */\n'
    '                        double *e = eg + g0;\n'
    '                        int mu;\n'
    '                        for (mu = 0; mu < nao; mu++) {\n'
    '                                const double *h = H + (size_t)mu * n, *gf = GF + (size_t)mu * n;\n'
    '#pragma omp simd\n'
    '                                for (g = 0; g < n; g++) e[g] += h[g] * gf[g];\n'
    '                        }\n'
    '                }\n')
rep('                                for (g = 0; g < n; g++) s += w[g] * d[g] * q[g];\n',
    '                                double *o_ = pp[x];\n'
    '                                for (g = 0; g < n; g++) {\n'
    '                                        const double t_ = w[g] * d[g] * q[g];\n'
    '                                        s += t_;\n'
    '                                        o_[g] += t_;\n'
    '                                }\n')
rep('free(R); free(Rwk);', 'free(R); free(V); free(Rwk);')
rep('const int clsp = pp->onec && cx_gcls;', 'const int clsp = 0;     /* GR_POINT needs the dense E, R */')

print('''/* generated by lib/dft/gen_cosx_grad_gr.py from SOCDFTcosx_grad of cosx.c: do not edit */
#define GR_POINT(E_, R_)                                                                                \\
        if (cx_gr_mode == 4) gr_point4(px, py, pz, (E_), (R_), W, V, nab, nh, n, sh, nhl, dgemm_);      \\
        else if (cx_gr_mode) gr_point2(px, py, pz, (E_), (R_), W, V, nab, nh, n, sh, nhl);
''')
print(body)
print('#undef GR_POINT')
